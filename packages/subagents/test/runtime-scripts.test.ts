import assert from "node:assert/strict";
import { mkdir, mkdtemp, readdir, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type * as NodeUrl from "node:url";
import { fileURLToPath } from "node:url";
import { afterEach, beforeEach, test, vi } from "vitest";
import type * as RuntimeBuilder from "../scripts/build-runtime.mjs";

// Redirect only the scripts' package-root discovery. The actual source modules, shared builder,
// esbuild, validation, publication and filesystem comparisons all execute unmodified.
const fixture = vi.hoisted(() => ({ root: "" }));
vi.mock("node:url", async (importOriginal) => {
  const actual = await importOriginal<typeof NodeUrl>();
  return {
    ...actual,
    fileURLToPath: (url: string | URL) => {
      const path = actual.fileURLToPath(url);
      return /\/subagents\/scripts\/(build|check)-runtime\.mjs$/u.test(path)
        ? join(fixture.root, "scripts", path.endsWith("/build-runtime.mjs") ? "build-runtime.mjs" : "check-runtime.mjs")
        : path;
    },
  };
});

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const originalArgv = [...process.argv];
const originalExitCode = process.exitCode;

beforeEach(async () => {
  vi.resetModules();
  fixture.root = await mkdtemp(join(tmpdir(), "subagents-runtime-scripts-"));
  await mkdir(join(fixture.root, "src"));
  await writeFile(join(fixture.root, "src/index.ts"), 'export const load = () => import("./lazy.js");\n');
  await writeFile(join(fixture.root, "src/lazy.ts"), 'export const value = "fixture";\n');
  process.exitCode = undefined;
});

afterEach(async () => {
  process.argv = [...originalArgv];
  process.exitCode = originalExitCode;
  vi.restoreAllMocks();
  await rm(fixture.root, { force: true, recursive: true });
});

/** Snapshot bytes and directory names, including hashed lazy chunks and their source maps. */
async function snapshot(root: string, prefix = ""): Promise<Record<string, string>> {
  const result: Record<string, string> = {};
  for (const entry of await readdir(join(root, prefix), { withFileTypes: true })) {
    const path = join(prefix, entry.name);
    if (entry.isDirectory()) Object.assign(result, await snapshot(root, path));
    else result[path] = await readFile(join(root, path), "base64");
  }
  return result;
}

async function assertCleanStaging(): Promise<void> {
  assert.deepEqual((await readdir(fixture.root)).filter((name) => name.startsWith(".pi-subagents-")), []);
}

test("direct build invocation publishes reproducible bytes and verification leaves them intact", async () => {
  process.argv[1] = join(packageRoot, "scripts/build-runtime.mjs");
  await vi.importActual<typeof RuntimeBuilder>("../scripts/build-runtime.mjs");
  const dist = join(fixture.root, "dist");
  const committed = await snapshot(dist);
  assert.ok(committed["index.ts"]);
  assert.ok(Object.keys(committed).some((name) => name.startsWith("chunks/") && name.endsWith(".ts.map")));
  assert.match(await readFile(join(dist, "index.ts"), "utf8"), /^\/\/ @generated by scripts\/build-runtime.mjs/u);
  await vi.importActual("../scripts/check-runtime.mjs");
  assert.equal(process.exitCode, undefined);
  assert.deepEqual(await snapshot(dist), committed);
  await assertCleanStaging();
});

test("import without an invoked path exports the real builder without publishing", async () => {
  process.argv = originalArgv.slice(0, 1);
  const builder = await vi.importActual<typeof RuntimeBuilder>("../scripts/build-runtime.mjs");
  assert.equal(typeof builder.validateEagerGraph, "function");
  assert.equal(typeof builder.validateGeneratedFiles, "function");
  assert.equal(typeof builder.publishRuntime, "function");
  assert.deepEqual(await readdir(fixture.root), ["src"]);
  await builder.buildRuntime();
  assert.ok((await snapshot(join(fixture.root, "dist")))["index.ts"]);
});

test("verification diagnoses missing, extra and stale files and does not repair committed output", async () => {
  const builder = await vi.importActual<typeof RuntimeBuilder>("../scripts/build-runtime.mjs");
  await builder.buildRuntime();
  const dist = join(fixture.root, "dist");
  await rm(join(dist, "index.ts.map"));
  await writeFile(join(dist, "extra.ts"), "extra");
  await writeFile(join(dist, "index.ts"), "stale");
  const committed = await snapshot(dist);
  const errors = vi.spyOn(console, "error").mockImplementation(() => undefined);
  await vi.importActual("../scripts/check-runtime.mjs");
  assert.equal(process.exitCode, 1);
  assert.equal(errors.mock.calls.length, 1);
  assert.equal(errors.mock.calls[0]?.[0],
    "dist/ is out of date, run `npm run build`:\nmissing: dist/index.ts.map\nextra: dist/extra.ts\nstale: dist/index.ts");
  assert.deepEqual(await snapshot(dist), committed);
  await assertCleanStaging();
});

test("verification fails closed when the committed runtime directory is absent", async () => {
  const errors = vi.spyOn(console, "error").mockImplementation(() => undefined);
  await vi.importActual("../scripts/check-runtime.mjs");
  assert.equal(process.exitCode, 1);
  assert.match(String(errors.mock.calls[0]?.[0]), /missing: dist\/index.ts/u);
  assert.deepEqual(await readdir(fixture.root), ["src"]);
});

test("verification propagates build refusal and cleans staging rather than admitting stale bytes", async () => {
  await writeFile(join(fixture.root, "src/index.ts"), 'export { absent } from "./missing.js";\n');
  vi.spyOn(console, "error").mockImplementation(() => undefined);
  await assert.rejects(vi.importActual("../scripts/check-runtime.mjs"), /Build failed/u);
  await assertCleanStaging();
});

test("subagents builder retains package-owned output, symlink and metadata refusals", async () => {
  const builder = await vi.importActual<typeof RuntimeBuilder>("../scripts/build-runtime.mjs");
  await assert.rejects(builder.buildRuntime({ outputDirectory: fixture.root }), /inside the package root and owned/u);
  const target = join(fixture.root, "target");
  await mkdir(target);
  await symlink(target, join(fixture.root, "dist"), "dir");
  await assert.rejects(builder.buildRuntime(), /must not be a symlink/u);
  assert.throws(() => builder.validateEagerGraph({}), /no src\/index.ts entrypoint/u);
  await assert.rejects(builder.validateGeneratedFiles(target), /missing index.ts/u);
  await assertCleanStaging();
});
