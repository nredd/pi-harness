import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const manifest = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const entry = readFileSync(new URL("../dist/index.ts", import.meta.url), "utf8");

/**
 * Pi's Jiti transforms every `src/` module on every launch; the pre-bundled `dist/index.ts`
 * only has to be evaluated (#577, ~300 ms of startup). The bundle is gitignored build
 * output (`npm run build`); these pin the properties that make it fast and loadable.
 */
describe("pre-bundled runtime entry", () => {
  it("is what Pi loads", () => {
    expect(manifest.pi.extensions).toEqual(["./dist/index.ts"]);
    expect(manifest.files).toEqual(expect.arrayContaining(["src", "dist"]));
  });

  it("is generated and a single eager unit", () => {
    expect(entry.startsWith("// @generated by scripts/build-runtime.mjs; do not edit.")).toBe(true);
    // Relative imports may only target lazy `./chunks/*`; none may reach back into `src/`.
    const relative = [...entry.matchAll(/from\s+"(\.{1,2}\/[^"]+)"/g)].map((match) => match[1]);
    expect(relative.filter((path) => !path.startsWith("./chunks/"))).toEqual([]);
  });

  it("keeps package dependencies external instead of bundling them", () => {
    expect(entry).toMatch(/from\s+"nanoid"/);
    expect(entry).toMatch(/from\s+"@earendil-works\/pi-coding-agent"/);
  });
});
