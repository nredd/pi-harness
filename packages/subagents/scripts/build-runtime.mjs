#!/usr/bin/env node

import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
// Repository-only build tool (not packed); plan-mode owns the shared builder, see its README.
import { createRuntimeBuilder } from "../../plan-mode/scripts/runtime-builder.mjs";

/**
 * `src/index.ts` is ~80 TypeScript modules (1.3 MB) that Pi's Jiti transforms on every launch,
 * about 300 ms of a 770 ms startup (#577). `dist/index.ts` is the same graph pre-bundled by
 * esbuild with `packages: "external"`, so Jiti only evaluates it.
 */
export const { buildRuntime, validateEagerGraph, validateGeneratedFiles, publishRuntime } = createRuntimeBuilder({
  packageRoot: resolve(dirname(fileURLToPath(import.meta.url)), ".."),
  temporaryPrefix: ".pi-subagents",
  banner: [
    "// @generated by scripts/build-runtime.mjs; do not edit.",
    "// @ts-nocheck -- the generated entry uses a .ts extension for Pi's Jiti loader.",
  ].join("\n"),
});

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : undefined;
if (invokedPath === import.meta.url) await buildRuntime();
